// Writes every factory preset as a standard .vstpreset file
// (<out>/<Plugin Name>/<Preset>.vstpreset), from the same preset tables the
// plug-ins compile in, plus a Lua table of expected parameter values for the
// REAPER preset test.
//
// usage: make_presets <output dir> [expectations.lua]

#include "ChoParams.h"
#include "CompParams.h"
#include "DessParams.h"
#include "DlyParams.h"
#include "EqParams.h"
#include "LimParams.h"
#include "RevParams.h"
#include "SatParams.h"

#include "suite/Brand.h"
#include "suite/Presets.h"
#include "suite/vst/ProcessorBase.h"

#include "base/source/fstreamer.h"
#include "public.sdk/source/common/memorystream.h"
#include "public.sdk/source/vst/vstpresetfile.h"

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <string>

using namespace Steinberg;
using namespace Steinberg::Vst;
namespace fs = std::filesystem;

namespace {

struct PluginInfo
{
	std::string name;
	FUID processorUID;
	const suite::ParamTable& table;
	const suite::PresetList& presets;
};

std::string fileSafe (std::string s)
{
	for (char& c : s)
		if (std::string ("\\/:*?\"<>|").find (c) != std::string::npos)
			c = '-';
	return s;
}

std::string luaString (const std::string& s)
{
	std::string out = "\"";
	for (char c : s)
		out += (c == '\\' || c == '"') ? std::string ("\\") + c : std::string (1, c);
	return out + "\"";
}

// Controller chunk: the UI state the editor reads, recording which factory
// preset this is so the preset bar shows its name after a host loads it.
void writeControllerState (IBStream* stream, int presetIndex)
{
	IBStreamer s (stream, kLittleEndian);
	s.writeInt32u (0x48535555); // 'HSUU', see ControllerBase
	s.writeInt32u (1);
	const std::string key = "preset";
	s.writeInt32u (static_cast<uint32> (key.size ()));
	s.writeRaw (key.data (), static_cast<int32> (key.size ()));
	s.writeDouble (presetIndex);
}

} // namespace

int main (int argc, char** argv)
{
	if (argc < 2)
	{
		std::printf ("usage: make_presets <output dir> [expectations.lua]\n");
		return 1;
	}
	const fs::path outDir = fs::u8path (argv[1]);
	std::ofstream lua;
	if (argc > 2)
	{
		lua.open (argv[2]);
		lua << "-- Generated by make_presets: expected normalized values per preset\nPRESETS = {\n";
	}

	const PluginInfo plugins[] = {
	    {SUITE_NAME " EQ", eq::kProcessorUID, eq::params (), eq::presets ()},
	    {SUITE_NAME " Compressor", comp::kProcessorUID, comp::params (), comp::presets ()},
	    {SUITE_NAME " De-Esser", dess::kProcessorUID, dess::params (), dess::presets ()},
	    {SUITE_NAME " Limiter", lim::kProcessorUID, lim::params (), lim::presets ()},
	    {SUITE_NAME " Reverb", rev::kProcessorUID, rev::params (), rev::presets ()},
	    {SUITE_NAME " Delay", dly::kProcessorUID, dly::params (), dly::presets ()},
	    {SUITE_NAME " Saturation", sat::kProcessorUID, sat::params (), sat::presets ()},
	    {SUITE_NAME " Chorus", cho::kProcessorUID, cho::params (), cho::presets ()},
	};

	int total = 0;
	for (auto& plugin : plugins)
	{
		const fs::path dir = outDir / fs::u8path (plugin.name);
		fs::create_directories (dir);
		for (int i = 0; i < static_cast<int> (plugin.presets.size ()); ++i)
		{
			const auto& preset = plugin.presets[i];
			const auto resolved = suite::resolvePreset (plugin.table, preset);
			auto normalizedOf = [&] (uint32_t id) {
				for (auto& [rid, value] : resolved)
					if (rid == id)
						return value;
				return suite::findSpec (plugin.table, id)->defaultNormalized ();
			};

			MemoryStream component, controller;
			suite::writeParamState (&component, plugin.table, normalizedOf);
			writeControllerState (&controller, i);
			component.seek (0, IBStream::kIBSeekSet, nullptr);
			controller.seek (0, IBStream::kIBSeekSet, nullptr);

			const fs::path file = dir / fs::u8path (fileSafe (preset.name) + ".vstpreset");
			auto stream = owned (FileStream::open (file.string ().c_str (), "wb"));
			if (!stream || !PresetFile::savePreset (stream, plugin.processorUID, &component, &controller))
			{
				std::printf ("FAILED: %s\n", file.string ().c_str ());
				return 2;
			}
			++total;

			if (lua.is_open ())
			{
				lua << "  {plugin = " << luaString (plugin.name) << ", preset = " << luaString (preset.name)
				    << ", file = " << luaString (file.string ()) << ", values = {";
				for (auto& [id, value] : resolved)
					lua << "{" << luaString (suite::findSpec (plugin.table, id)->name) << ", " << value << "}, ";
				lua << "}},\n";
			}
		}
		std::printf ("%-20s %2zu presets\n", plugin.name.c_str (), plugin.presets.size ());
	}
	if (lua.is_open ())
		lua << "}\n";
	std::printf ("total: %d presets\n", total);
	return 0;
}
